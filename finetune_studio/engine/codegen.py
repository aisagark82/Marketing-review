def gen_launch(cfg):
    W, nodes = world_size(cfg), int(cfg.get("num_nodes") or 1)
    per = int(cfg.get("num_gpus") or 1)
    L = ["#!/usr/bin/env bash", f"# {cfg['project_name']}: {cfg['objective']} / {cfg['method']} on {W}× {cfg['gpu_type']} ({resolve_strategy(cfg)})", "set -euo pipefail"]
    if cfg.get("platform") == "slurm":
        L = ["#!/usr/bin/env bash", f"#SBATCH --job-name={cfg['project_name']}", f"#SBATCH --nodes={nodes}", "#SBATCH --ntasks-per-node=1",
             f"#SBATCH --gres=gpu:{per}", "#SBATCH --cpus-per-task=32", "#SBATCH --time=48:00:00", "#SBATCH --output=logs/%x-%j.out",
             "#SBATCH --requeue  # resubmit on preemption", "set -euo pipefail",
             "export MASTER_ADDR=$(scontrol show hostnames $SLURM_JOB_NODELIST | head -n1)", "export MASTER_PORT=29500"]
    L += ["export TOKENIZERS_PARALLELISM=false", "export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True", ""]
    launcher = cfg.get("launcher", "accelerate")
    multi = "--machine_rank $SLURM_NODEID --main_process_ip $MASTER_ADDR --main_process_port $MASTER_PORT " if (nodes > 1 and cfg.get("platform") == "slurm") else ""
    if launcher == "accelerate":
        cmd = f"accelerate launch --config_file accelerate_config.yaml {multi}train.py"
    elif launcher == "torchrun":
        cmd = f"torchrun --nnodes {nodes} --nproc_per_node {per}" + (" --rdzv_backend c10d --rdzv_endpoint $MASTER_ADDR:$MASTER_PORT" if nodes > 1 else "") + " train.py"
    else:
        cmd = f"deepspeed --num_gpus {per} --num_nodes {nodes} train.py"
    if cfg.get("preflight_checks") and cfg.get("preflight_block"):
        L += ["# fine-tuning sanity checks (minutes, one GPU) — abort before burning GPU hours", "python ft_checks.py || { echo 'ft_checks failed: fix before training'; exit 1; }", ""]
    L.append(("srun " if cfg.get("platform") == "slurm" else "") + cmd)
    if cfg.get("ckpt_selection") in ("best_task_metric", "soup") or cfg.get("ft_diagnostics") or cfg.get("objective_tests") or cfg.get("technique_tests"):
        L.append("python ft_diagnostics.py  # checkpoint selection + fine-tuning diagnostics")
    L += ["", "# then: bash eval.sh && bash export.sh && bash serve.sh"]
    return "\n".join(L) + "\n"


