def full_config(cfg):
    c = defaults()
    c.update({k: v for k, v in (cfg or {}).items()})
    return c


def _y(v):
    return json.dumps(v, ensure_ascii=False)


def to_yaml(cfg):
    lines = ["# Fine-Tune Studio config — JSON values are valid YAML", ""]
    seen = set()
    for st in STAGES:
        lines.append(f"# ── {st['title']} ──")
        for s in st["sections"]:
            for f in s["fields"]:
                k = f["key"]
                seen.add(k)
                lines.append(f"{k}: {_y(cfg.get(k))}")
        lines.append("")
    extra = [k for k in cfg if k not in seen]
    if extra:
        lines.append("# ── other ──")
        lines += [f"{k}: {_y(cfg[k])}" for k in extra]
    return "\n".join(lines) + "\n"


def run_name(cfg):
    try:
        return str(cfg.get("run_name") or "{project}").format(project=cfg.get("project_name", "run"), **{k: v for k, v in cfg.items() if k != "project"})
    except (KeyError, IndexError, ValueError):
        return cfg.get("project_name", "run")


def _model_id(cfg):
    return cfg.get("custom_model_id") if cfg.get("base_model") == "custom" else cfg.get("base_model")


def _trainer_imports(obj):
    exp = {
        "orpo": ("ORPOConfig", "ORPOTrainer", "orpo"), "simpo": ("CPOConfig", "CPOTrainer", "cpo"), "cpo": ("CPOConfig", "CPOTrainer", "cpo"),
        "kto": ("KTOConfig", "KTOTrainer", "kto"), "ppo": ("PPOConfig", "PPOTrainer", "ppo"), "rloo": ("RLOOConfig", "RLOOTrainer", "rloo"),
        "distill": ("GKDConfig", "GKDTrainer", "gkd"),
    }
    std = {"sft": ("SFTConfig", "SFTTrainer"), "cpt": ("SFTConfig", "SFTTrainer"), "dpo": ("DPOConfig", "DPOTrainer"),
           "grpo": ("GRPOConfig", "GRPOTrainer"), "reward_model": ("RewardConfig", "RewardTrainer")}
    if obj in std:
        c, t = std[obj]
        return f"from trl import {c}, {t}", c, t
    if obj in exp:
        c, t, mod = exp[obj]
        return (f"try:\n    from trl import {c}, {t}\nexcept ImportError:  # newer TRL moved it\n"
                f"    from trl.experimental.{mod} import {c}, {t}"), c, t
    return "from transformers import Trainer, TrainingArguments", "TrainingArguments", "Trainer"


def _call(head, args, tail=""):
    """Render `head(\n    a,\n    b,  # comment\n)` keeping trailing comments after the comma."""
    out = []
    for x in args:
        code, sep, comment = x.partition("  # ")
        out.append(f"    {code}," + (f"  # {comment}" if sep else ""))
    return f"{head}(\n" + "\n".join(out) + (f"\n    {tail.lstrip(', ')}," if tail else "") + "\n)"


def gen_train(cfg):
    m, obj = cfg["method"], cfg["objective"]
    mid = _model_id(cfg)
    imp, Cfg, Trn = _trainer_imports(obj)
    bf16 = cfg["precision"] == "bf16"
    dtype = "torch.bfloat16" if cfg["precision"] in ("bf16", "fp8") else "torch.float16" if cfg["precision"] == "fp16" else "torch.float32"
    L = []
    w = L.append

    w(f'"""{cfg["project_name"]} — generated by Fine-Tune Studio.')
    w(f"Objective: {obj} · method: {m} · base: {mid}")
    w('Run via launch.sh (handles single / multi-GPU). Edit freely: every value comes from config.yaml."""')
    w("import hashlib\nimport json\nimport os\nimport re\n\nimport torch\nfrom datasets import load_dataset, interleave_datasets")
    cls = obj == "classifier"
    w("from transformers import AutoTokenizer, " + ("AutoModelForSequenceClassification" if cls else "AutoModelForCausalLM")
      + (", BitsAndBytesConfig" if m == "qlora" else "") + ", EarlyStoppingCallback, set_seed")
    peft_imports = {
        "lora": "LoraConfig", "qlora": "LoraConfig, prepare_model_for_kbit_training", "dora": "LoraConfig",
        "adalora": "AdaLoraConfig", "vera": "VeraConfig", "ia3": "IA3Config", "prefix": "PrefixTuningConfig",
        "prompt_tuning": "PromptTuningConfig, PromptTuningInit",
    }
    if m in peft_imports:
        w(f"from peft import {peft_imports[m]}" + (", get_peft_model" if cls else ""))
    w(imp)
    if cls:
        w("from transformers import DataCollatorWithPadding")
    w("")
    w("import dataclasses\n")
    w("RENAMED = {'warmup_ratio': 'warmup_steps'}  # Transformers 5: warmup_steps accepts a ratio < 1")
    w("def compat(cls, kw):")
    w('    """Keep this script working across Transformers / TRL versions: map renamed options, report unsupported ones."""')
    w("    fields = {f.name for f in dataclasses.fields(cls)}")
    w("    out = {}")
    w("    for k, v in kw.items():")
    w("        if k not in fields and RENAMED.get(k) in fields:")
    w("            k = RENAMED[k]")
    w("        if k in fields:")
    w("            out[k] = v")
    w("        else:")
    w("            print(f'[compat] {cls.__name__} in this TRL/Transformers version has no {k!r} — ignored ({k}={v!r})')")
    w("    return out")
    w("")
    w(f"MODEL_ID = {mid!r}")
    w(f"REVISION = {cfg.get('model_revision') or 'main'!r}")
    w(f"DATA = {cfg['data_path']!r}")
    w(f"OUTPUT_DIR = os.environ.get('FT_OUTPUT_DIR', {'outputs/' + cfg['project_name']!r})")
    w("OVR = json.loads(os.environ.get('FT_OVERRIDES') or '{}')  # hyperparameter overrides from sweep.py")
    w(f"RUN_NAME = {run_name(cfg)!r}")
    w(f"SEED = {int(cfg['seed'])}")
    w("set_seed(SEED)")
    if cfg["tracker"] == "wandb":
        w(f"os.environ.setdefault('WANDB_PROJECT', {cfg['tracker_project']!r})")
        w(f"os.environ.setdefault('WANDB_LOG_MODEL', {str(cfg.get('log_model', 'end'))!r})")
    elif cfg["tracker"] == "mlflow":
        w(f"os.environ.setdefault('MLFLOW_EXPERIMENT_NAME', {cfg['tracker_project']!r})")
    if cfg.get("tf32"):
        w("torch.backends.cuda.matmul.allow_tf32 = True")
    w("")

    # ── data
    w("# ─────────────────────────── data ───────────────────────────")
    src = cfg["data_source"]
    w("def load(path):")
    if src == "hf_hub":
        w(f"    return load_dataset(path, split='train', revision={cfg.get('data_revision') or None!r})")
    else:
        w("    ext = path.rsplit('.', 1)[-1].lower()")
        w("    kind = {'jsonl': 'json', 'json': 'json', 'csv': 'csv', 'tsv': 'csv', 'parquet': 'parquet', 'arrow': 'arrow'}.get(ext, 'json')")
        w("    return load_dataset(kind, data_files=path, split='train')" + ("  # s3:// gs:// az:// work via fsspec" if src == "object_store" else ""))
    w("")
    mix = [ln.split() for ln in str(cfg.get("data_mixing") or "").splitlines() if ln.strip()]
    if mix:
        main_w = max(0.0, 1 - sum(float(x[1]) for x in mix if len(x) > 1))
        srcs = [("DATA", round(main_w, 4))] + [(repr(x[0]), float(x[1]) if len(x) > 1 else 0.1) for x in mix]
        w("SOURCES = [" + ", ".join(f"({p}, {wt})" for p, wt in srcs) + "]")
        w("SOURCES = [(p, wt) for p, wt in SOURCES if p != os.environ.get('FT_EXCLUDE_SOURCE')]  # leave-one-out ablation (sweep.py)")
        w("_tot = sum(wt for _, wt in SOURCES)")
        w("ds = interleave_datasets([load(p) for p, _ in SOURCES], probabilities=[wt / _tot for _, wt in SOURCES], seed=SEED,\n"
          "                         stopping_strategy='all_exhausted') if len(SOURCES) > 1 else load(SOURCES[0][0])")
    else:
        w("ds = load(DATA)")
    w("")
    w(f"tok = AutoTokenizer.from_pretrained(MODEL_ID, revision=REVISION, trust_remote_code={bool(cfg.get('trust_remote_code'))})")
    pad = cfg.get("pad_token", "eos")
    if pad == "new":
        w("tok.add_special_tokens({'pad_token': '[PAD]'})")
    else:
        w(f"if tok.pad_token is None:\n    tok.pad_token = tok.{'unk' if pad == 'unk' else 'eos'}_token")
    w(f"tok.padding_side = {cfg.get('padding_side', 'right')!r}")
    w(f"tok.truncation_side = {cfg.get('truncation_side', 'right')!r}")
    if cfg.get("add_special_tokens"):
        toks = [t.strip() for t in str(cfg["add_special_tokens"]).split(",") if t.strip()]
        w(f"tok.add_special_tokens({{'additional_special_tokens': {toks!r}}})")
    if cfg.get("chat_template") == "custom" and cfg.get("custom_template"):
        w(f"tok.chat_template = {cfg['custom_template']!r}")
    elif cfg.get("chat_template") not in (None, "model_default"):
        w(f"# chat_template = {cfg['chat_template']!r}: set tok.chat_template to that template if the model lacks one")
    w("")

    schema = cfg["record_schema"]
    sysmsg = cfg.get("system_prompt") or ""
    if schema == "alpaca" and obj in ("sft", "distill"):
        w("def to_messages(r):")
        w("    user = r['instruction'] + (('\\n\\n' + r['input']) if r.get('input') else '')")
        w(f"    msgs = ([{{'role': 'system', 'content': {sysmsg!r}}}] if {bool(sysmsg)} else []) + [")
        w("        {'role': 'user', 'content': user}, {'role': 'assistant', 'content': r['output']}]")
        w("    return {'messages': msgs}")
        w("ds = ds.map(to_messages, remove_columns=ds.column_names)")
    elif schema == "messages" and sysmsg:
        w("def add_system(r):")
        w(f"    if r['messages'] and r['messages'][0]['role'] != 'system':\n        r['messages'] = [{{'role': 'system', 'content': {sysmsg!r}}}] + r['messages']")
        w("    return r")
        w("ds = ds.map(add_system)")

    w("")
    w("def text_of(r):")
    w("    return ' '.join(str(m.get('content', '')) if isinstance(m, dict) else str(m)")
    w("                    for v in r.values() for m in (v if isinstance(v, list) else [v]))")
    if cfg.get("dedup") == "exact":
        w("\nseen = set()")
        w("def first_time(r):")
        w("    h = hashlib.md5(text_of(r).strip().lower().encode()).hexdigest()")
        w("    if h in seen:\n        return False\n    seen.add(h)\n    return True")
        w("ds = ds.filter(first_time)  # exact dedup (single process)")
    elif cfg.get("dedup") in ("minhash", "semantic"):
        w(f"# {cfg['dedup']} dedup: run datatrove / text-dedup beforehand (threshold {cfg.get('minhash_threshold')})")
    mn, mx = int(cfg.get("min_tokens") or 0), int(cfg.get("max_tokens_filter") or 0)
    if mn or mx:
        w(f"ds = ds.filter(lambda r: {mn} <= len(tok(text_of(r)).input_ids)" + (f" <= {mx}" if mx else "") + f", num_proc={int(cfg['num_proc'])})")
    if cfg.get("pii_scrub") == "regex":
        w("EMAIL = re.compile(r'[\\w.+-]+@[\\w-]+\\.[\\w.-]+')")
        w("PHONE = re.compile(r'(?<!\\d)(?:\\+?\\d[\\s-]?){9,14}\\d(?!\\d)')")
        w("def scrub(x):")
        w("    if isinstance(x, str):\n        return PHONE.sub('<PHONE>', EMAIL.sub('<EMAIL>', x))")
        w("    if isinstance(x, list):\n        return [scrub(i) for i in x]")
        w("    if isinstance(x, dict):\n        return {k: scrub(v) for k, v in x.items()}")
        w("    return x")
        w(f"ds = ds.map(lambda r: {{k: scrub(v) for k, v in r.items()}}, num_proc={int(cfg['num_proc'])})")
    elif cfg.get("pii_scrub") in ("presidio", "llm"):
        w(f"# PII scrubbing via {cfg['pii_scrub']}: apply before training (see presidio-analyzer)")
    if cfg.get("quality_filter") not in (None, "none"):
        w(f"# quality filter '{cfg['quality_filter']}' (threshold {cfg.get('quality_threshold')}): precompute a score column and filter here")
    if cfg.get("decontaminate"):
        w(f"# decontamination: drop examples sharing {cfg.get('decontam_ngram', 13)}-grams with eval sets (lm-eval decontamination tooling)")
    if cfg.get("augmentation"):
        w(f"# augmentation {cfg['augmentation']} with teacher {cfg.get('teacher_model')!r}: generate offline, then append to DATA")
    w("")
    val, test = float(cfg["val_ratio"]), float(cfg["test_ratio"])
    strat = cfg.get("split_strategy")
    key = cfg.get("split_group_key") or "label"
    w("# ── splits (test split is written to disk for eval_suite.py)")
    if strat == "temporal":
        w(f"ds = ds.sort({key!r})")
        w(f"n = len(ds); n_test, n_val = int(n * {test}), int(n * {val})")
        w("test_ds = ds.select(range(n - n_test, n))")
        w("eval_ds = ds.select(range(n - n_test - n_val, n - n_test))")
        w("train_ds = ds.select(range(0, n - n_test - n_val))")
    else:
        sk = f", stratify_by_column={key!r}" if strat == "stratified" else ""
        if strat == "group":
            w(f"# grouped split on {key!r}: keep every group in one split to avoid leakage")
            w(f"groups = sorted(set(ds[{key!r}]))")
            w("import random; random.Random(SEED).shuffle(groups)")
            w(f"ng = len(groups); test_g = set(groups[:int(ng * {test})]); val_g = set(groups[int(ng * {test}):int(ng * {test + val})])")
            w(f"test_ds = ds.filter(lambda r: r[{key!r}] in test_g)")
            w(f"eval_ds = ds.filter(lambda r: r[{key!r}] in val_g)")
            w(f"train_ds = ds.filter(lambda r: r[{key!r}] not in test_g and r[{key!r}] not in val_g)")
        else:
            if strat == "stratified":
                w(f"ds = ds.class_encode_column({key!r})")
            w(f"s1 = ds.train_test_split(test_size={round(val + test, 4)}, seed={int(cfg['split_seed'])}{sk})")
            w(f"s2 = s1['test'].train_test_split(test_size={round(test / (val + test), 4) if val + test else 0.5}, seed={int(cfg['split_seed'])}{sk})")
            w("train_ds, eval_ds, test_ds = s1['train'], s2['train'], s2['test']")
    w("FRACTION = float(os.environ.get('FT_DATA_FRACTION', '1'))  # learning-curve runs (sweep.py)")
    w("if FRACTION < 1:\n    train_ds = train_ds.shuffle(seed=SEED).select(range(max(1, int(len(train_ds) * FRACTION))))")
    w("os.makedirs(OUTPUT_DIR, exist_ok=True)")
    w("test_ds.to_json(os.path.join(OUTPUT_DIR, 'test.jsonl'))")
    w("eval_ds.to_json(os.path.join(OUTPUT_DIR, 'val.jsonl'))  # checkpoint selection & diagnostics use validation only")
    if cfg.get("curriculum") == "length":
        w("train_ds = train_ds.map(lambda r: {'_len': len(text_of(r))}).sort('_len').remove_columns('_len')  # curriculum")
    w("")

    # ── model
    w("# ─────────────────────────── model ───────────────────────────")
    if m == "qlora":
        if int(cfg.get("quant_bits", 4)) == 4:
            w("bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type=" + repr(cfg.get("quant_type", "nf4"))
              + f", bnb_4bit_use_double_quant={bool(cfg.get('double_quant', True))}, bnb_4bit_compute_dtype=torch.{cfg.get('compute_dtype', 'bfloat16')}"
              + (", bnb_4bit_quant_storage=torch.bfloat16" if cfg.get("quant_storage") == "bfloat16" else "") + ")")
        else:
            w("bnb = BitsAndBytesConfig(load_in_8bit=True)")
    kw = [f"revision=REVISION", f"dtype={dtype}", f"attn_implementation={cfg['attn_impl']!r}",
          f"trust_remote_code={bool(cfg.get('trust_remote_code'))}"]
    if m == "qlora":
        kw.append("quantization_config=bnb")
    if cfg.get("rope_scaling", "none") != "none":
        kw.append(f"rope_scaling={{'type': {cfg['rope_scaling']!r}, 'factor': {float(cfg.get('rope_factor', 2.0))}}}")
    if cls:
        kw.append(f"num_labels={int(cfg.get('num_labels', 2))}")
        if cfg.get("problem_type") == "multi_label":
            kw.append("problem_type='multi_label_classification'")
        elif cfg.get("problem_type") == "regression":
            kw.append("problem_type='regression'")
    Auto = "AutoModelForSequenceClassification" if cls else "AutoModelForCausalLM"
    w(_call(f"model = {Auto}.from_pretrained", ["MODEL_ID"] + kw))
    if cls:
        w("model.config.pad_token_id = tok.pad_token_id")
    if pad == "new" or cfg.get("add_special_tokens"):
        w("model.resize_token_embeddings(len(tok), pad_to_multiple_of=64)")
    if m == "qlora":
        w(f"model = prepare_model_for_kbit_training(model, use_gradient_checkpointing={cfg['grad_checkpointing'] != 'off'})")
    if m == "freeze":
        n_top = int(cfg.get("trainable_layers", 4))
        w(f"# partial fine-tuning: train only the top {n_top} decoder layers")
        w("for p in model.parameters():\n    p.requires_grad = False")
        w(f"for layer in model.model.layers[-{n_top}:]:\n    for p in layer.parameters():\n        p.requires_grad = True")
        if cfg.get("train_lm_head", True):
            w("for p in model.lm_head.parameters():\n    p.requires_grad = True")
        if cfg.get("train_embeddings"):
            w("for p in model.get_input_embeddings().parameters():\n    p.requires_grad = True")
    if m == "bitfit":
        w("# BitFit: train only bias terms (note: many modern LLMs have no biases)")
        w("for n_, p in model.named_parameters():\n    p.requires_grad = n_.endswith('.bias')")
    w("")

    # ── peft
    peft = "None"
    task = "SEQ_CLS" if cls else "CAUSAL_LM"
    if m in PEFT_LORA:
        tm = cfg.get("target_modules") or ["all-linear"]
        tm_s = "'all-linear'" if "all-linear" in tm else repr([t for t in tm if t not in ("embed_tokens", "lm_head")] + [t for t in tm if t in ("embed_tokens", "lm_head")])
        init = cfg.get("lora_init", "default")
        init_s = {"default": "True", "gaussian": "'gaussian'", "pissa": "'pissa_niter_16'", "olora": "'olora'", "loftq": "'loftq'", "eva": "'eva'"}[init]
        args = [f"r={int(cfg['lora_r'])}", f"lora_alpha={int(cfg['lora_alpha'])}", f"lora_dropout={float(cfg['lora_dropout'])}",
                f"target_modules={tm_s}", f"bias={cfg.get('lora_bias', 'none')!r}", f"task_type={task!r}"]
        if init != "default":
            args.append(f"init_lora_weights={init_s}")
        if cfg.get("use_rslora"):
            args.append("use_rslora=True")
        if m == "dora":
            args.append("use_dora=True")
        mts = [x.strip() for x in str(cfg.get("modules_to_save") or "").split(",") if x.strip()]
        if cls:
            mts = mts or ["score"]
        if mts:
            args.append(f"modules_to_save={mts!r}")
        ltt = [int(x) for x in str(cfg.get("layers_to_transform") or "").split(",") if x.strip().isdigit()]
        if ltt:
            args.append(f"layers_to_transform={ltt!r}")
        if m == "adalora":
            args = [a_ for a_ in args if not a_.startswith(("r=", "use_dora", "use_rslora"))]
            args += [f"init_r={int(cfg.get('adalora_init_r', 12))}", f"target_r={int(cfg.get('adalora_target_r', 8))}", "total_step=None  # set to total optimizer steps"]
            w(_call("peft_config = AdaLoraConfig", args))
        else:
            w(_call("peft_config = LoraConfig", args))
        peft = "peft_config"
    elif m == "vera":
        w(f"peft_config = VeraConfig(r={int(cfg.get('vera_r', 256))}, target_modules=['q_proj', 'v_proj', 'gate_proj', 'up_proj', 'down_proj'], task_type={task!r})")
        peft = "peft_config"
    elif m == "ia3":
        w(f"peft_config = IA3Config(target_modules=['k_proj', 'v_proj', 'down_proj'], feedforward_modules=['down_proj'], task_type={task!r})")
        peft = "peft_config"
    elif m == "prefix":
        w(f"peft_config = PrefixTuningConfig(num_virtual_tokens={int(cfg['num_virtual_tokens'])}, task_type={task!r})")
        peft = "peft_config"
    elif m == "prompt_tuning":
        if cfg.get("prompt_init") == "text" and cfg.get("prompt_init_text"):
            w(f"peft_config = PromptTuningConfig(num_virtual_tokens={int(cfg['num_virtual_tokens'])}, prompt_tuning_init=PromptTuningInit.TEXT,\n"
              f"    prompt_tuning_init_text={cfg['prompt_init_text']!r}, tokenizer_name_or_path=MODEL_ID, task_type={task!r})")
        else:
            w(f"peft_config = PromptTuningConfig(num_virtual_tokens={int(cfg['num_virtual_tokens'])}, prompt_tuning_init=PromptTuningInit.RANDOM, task_type={task!r})")
        peft = "peft_config"
    if m in PEFT_LORA and m != "adalora":
        w("for k_, attr_ in {'lora_r': 'r', 'lora_alpha': 'lora_alpha', 'lora_dropout': 'lora_dropout'}.items():\n"
          "    if k_ in OVR:\n        setattr(peft_config, attr_, OVR[k_])")
    w("")

    # ── rewards (online RL)
    if obj in ("grpo", "rloo", "ppo"):
        w("# ─────────────────────────── rewards ───────────────────────────")
        rs = cfg.get("reward_sources") or []
        funcs = []
        if "accuracy" in rs:
            funcs.append("accuracy_reward")
            w("def _final_answer(text):")
            w("    m = re.findall(r'\\\\boxed\\{([^}]*)\\}', text) or re.findall(r'####\\s*(.+)', text) or re.findall(r'<answer>(.*?)</answer>', text, re.S)")
