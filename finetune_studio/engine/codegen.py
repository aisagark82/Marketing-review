def gen_ds_config(cfg):
    st = resolve_strategy(cfg)
    stage = {"zero1": 1, "zero2": 2, "zero3": 3, "zero3_offload": 3}.get(st)
    if not stage:
        return None
    z = {"stage": stage, "overlap_comm": True, "contiguous_gradients": True, "reduce_bucket_size": "auto"}
    if stage == 3:
        z.update(stage3_prefetch_bucket_size="auto", stage3_param_persistence_threshold="auto", stage3_gather_16bit_weights_on_model_save=True)
    if st == "zero3_offload" or cfg.get("offload_optimizer"):
        z["offload_optimizer"] = {"device": "cpu", "pin_memory": True}
    if st == "zero3_offload":
        z["offload_param"] = {"device": "cpu", "pin_memory": True}
    conf = {"bf16": {"enabled": "auto"}, "fp16": {"enabled": "auto"}, "zero_optimization": z,
            "gradient_accumulation_steps": "auto", "gradient_clipping": "auto",
            "train_batch_size": "auto", "train_micro_batch_size_per_gpu": "auto"}
    if cfg.get("seq_parallel") == "ulysses":
        conf["sequence_parallel_size"] = world_size(cfg)
    return json.dumps(conf, indent=2) + "\n"


